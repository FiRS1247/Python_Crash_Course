# Agregar un tabulador antes de la palabra
palabra = "python"

print("\t" + palabra)
print("\tpython")
print("python")

# Agregar salots de linea

print("Lenguajes de programacion:\nPython\nC\nJavaScript")

# Agregar saltos de linea y tabuladores juntos
print("Lenguajes de programacion:\n\tPython\n\tC\n\tJavaScript")

# Quitar espacios innecesarios en blanco de un string
lenguajels = " python "

# Quitar espacio a la derecha

print("mi lenguaje favorito es " + lenguajels.rstrip())

# Quitar espacio a la izquierda

print("mi lenguaje favorito es " + lenguajels.lstrip())

# Quitar espacio de los ambos lados

print("mi lenguaje favorito es " + lenguajels.strip())
