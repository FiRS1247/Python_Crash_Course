# Poner mayusculas al inicio e cada palabra
nombre = "ada lovelace"
print(nombre.title())

# Poner todo en mayusculas
print(nombre.upper())

# Poner todo en minusculas
print(nombre.lower())

# Poner mayuscula la primera letra
print(nombre.capitalize())

# Uso de variables en stings
primer_nombre = "ada"
apellido = "lovelace"

nombre_completo = f"{primer_nombre} {apellido}"
print(nombre_completo)
